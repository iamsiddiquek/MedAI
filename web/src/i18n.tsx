export const dictionaries: Record<Lang, Record<Key, string>> = { en, ar };

interface I18n { lang: Lang; t: (key: Key) => string; error: (code: string) => string; toggle: () => void }

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children, initial = "en" }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLang] = useState<Lang>(initial);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  const t = useCallback((key: Key) => dictionaries[lang][key], [lang]);
  const error = useCallback((code: string) => {
    const key = `err_${code}`;
    return key in dictionaries[lang] ? dictionaries[lang][key as Key] : dictionaries[lang].err_generic;
  }, [lang]);
  const value = useMemo(() => ({ lang, t, error, toggle: () => setLang((l) => (l === "en" ? "ar" : "en")) }),
    [lang, t, error]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const value = useContext(Ctx);
  if (!value) throw new Error("I18nProvider is missing");
  return value;
}
